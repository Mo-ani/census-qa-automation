package com.census.qa.model;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;

import java.time.LocalDate;

/**
 * One person of a household - the canonical test model.
 *
 * <p>The same person is represented differently on each layer (form fields on the UI,
 * JSON in the API, columns of the "Record" and "Relative" tables in the database).
 * {@link RecordMapper} converts every one of those representations into this POJO, so
 * a single object comparison verifies all submitted values at once.
 *
 * <p>The enum-like values (relationship, gender, ...) are kept as the exact upper-case
 * text the application uses, e.g. {@code BIOLOGICAL_CHILD}; it is the text shown in the
 * drop-downs, returned by the API and stored in the database.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
@JsonInclude(JsonInclude.Include.NON_NULL)
public class PersonRecord {

    /** Primary key of the "Record" table - generated by the application, unknown on the UI. */
    private Integer id;
    private Integer householdId;

    private String relationship;
    private String firstName;
    private String lastName;
    @JsonFormat(pattern = "yyyy-MM-dd")
    private LocalDate dob;
    private String gender;
    private String telephone;
    private String hispanic;
    private String hispanicOther;
    private String race;
    private String raceOther;
    private String otherStay;

    public PersonRecord() {
    }

    /** Copy constructor - used to derive the "after update" state from the original record. */
    public PersonRecord(PersonRecord other) {
        this.id = other.id;
        this.householdId = other.householdId;
        this.relationship = other.relationship;
        this.firstName = other.firstName;
        this.lastName = other.lastName;
        this.dob = other.dob;
        this.gender = other.gender;
        this.telephone = other.telephone;
        this.hispanic = other.hispanic;
        this.hispanicOther = other.hispanicOther;
        this.race = other.race;
        this.raceOther = other.raceOther;
        this.otherStay = other.otherStay;
    }

    public String fullName() {
        return firstName + " " + lastName;
    }

    public Integer getId() {
        return id;
    }

    public PersonRecord setId(Integer id) {
        this.id = id;
        return this;
    }

    public Integer getHouseholdId() {
        return householdId;
    }

    public PersonRecord setHouseholdId(Integer householdId) {
        this.householdId = householdId;
        return this;
    }

    public String getRelationship() {
        return relationship;
    }

    public PersonRecord setRelationship(String relationship) {
        this.relationship = relationship;
        return this;
    }

    public String getFirstName() {
        return firstName;
    }

    public PersonRecord setFirstName(String firstName) {
        this.firstName = firstName;
        return this;
    }

    public String getLastName() {
        return lastName;
    }

    public PersonRecord setLastName(String lastName) {
        this.lastName = lastName;
        return this;
    }

    public LocalDate getDob() {
        return dob;
    }

    public PersonRecord setDob(LocalDate dob) {
        this.dob = dob;
        return this;
    }

    public String getGender() {
        return gender;
    }

    public PersonRecord setGender(String gender) {
        this.gender = gender;
        return this;
    }

    public String getTelephone() {
        return telephone;
    }

    public PersonRecord setTelephone(String telephone) {
        this.telephone = telephone;
        return this;
    }

    public String getHispanic() {
        return hispanic;
    }

    public PersonRecord setHispanic(String hispanic) {
        this.hispanic = hispanic;
        return this;
    }

    public String getHispanicOther() {
        return hispanicOther;
    }

    public PersonRecord setHispanicOther(String hispanicOther) {
        this.hispanicOther = hispanicOther;
        return this;
    }

    public String getRace() {
        return race;
    }

    public PersonRecord setRace(String race) {
        this.race = race;
        return this;
    }

    public String getRaceOther() {
        return raceOther;
    }

    public PersonRecord setRaceOther(String raceOther) {
        this.raceOther = raceOther;
        return this;
    }

    public String getOtherStay() {
        return otherStay;
    }

    public PersonRecord setOtherStay(String otherStay) {
        this.otherStay = otherStay;
        return this;
    }

    @Override
    public String toString() {
        return "PersonRecord{id=" + id
                + ", relationship=" + relationship
                + ", firstName=" + firstName
                + ", lastName=" + lastName
                + ", dob=" + dob
                + ", gender=" + gender
                + ", telephone=" + telephone
                + ", hispanic=" + hispanic
                + ", hispanicOther=" + hispanicOther
                + ", race=" + race
                + ", raceOther=" + raceOther
                + ", otherStay=" + otherStay
                + ", householdId=" + householdId + '}';
    }
}
