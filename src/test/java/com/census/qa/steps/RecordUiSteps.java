package com.census.qa.steps;

import com.census.qa.context.TestContext;
import com.census.qa.model.PersonRecord;
import com.census.qa.model.RecordMapper;
import com.census.qa.pages.DashboardPage;
import com.census.qa.pages.DeleteRecordDialog;
import com.census.qa.pages.LoginPage;
import com.census.qa.pages.RecordDialog;
import com.census.qa.utils.PersonStorage;
import com.census.qa.utils.TestDataFactory;
import io.cucumber.datatable.DataTable;
import io.cucumber.java.en.Given;
import io.cucumber.java.en.Then;
import io.cucumber.java.en.When;

import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * UI steps. They only describe WHAT the user does; HOW (locators, waits) is in the page objects.
 */
public class RecordUiSteps {

    /** Fields the UI cannot show: both are generated by the application. */
    private static final String[] NOT_ON_THE_CARD = {"id", "householdId"};

    private final TestContext context;

    private DashboardPage dashboard;
    private RecordDialog recordDialog;
    private DeleteRecordDialog deleteDialog;

    public RecordUiSteps(TestContext context) {
        this.context = context;
    }

    @Given("the user is logged in to the Census app")
    public void theUserIsLoggedIn() {
        dashboard = new LoginPage(context.driver())
                .open()
                .loginAs(context.user().getEmail(), context.user().getPassword());
    }

    // --- add ----------------------------------------------------------------------

    /**
     * Fields that are not in the table keep a valid default; first and last name are generated
     * (unique, starting with FAKE) unless the table sets them.
     */
    @When("the user adds a new person record with:")
    public void theUserAddsANewPersonRecordWith(DataTable table) {
        PersonRecord person = TestDataFactory.validPerson("OTHER_RELATIVE");
        RecordMapper.applyTable(person, withGeneratedValues(table));
        context.setPerson(person);

        recordDialog = dashboard.openAddRecordDialog().fill(person).submit();
    }

    @When("the user submits a new person record with {word} {string}")
    public void theUserSubmitsANewPersonRecordWithInvalid(String field, String invalidValue) {
        PersonRecord person = TestDataFactory.validPerson("OTHER_RELATIVE");
        context.setPerson(person);
        if ("dob".equals(field)) {
            // The date can only be picked in a calendar, so the one invalid input a user can give is none
            assertThat(invalidValue).as("the only invalid dob the UI allows is an empty one").isEmpty();
            person.setDob(null);
        }

        recordDialog = dashboard.openAddRecordDialog().fill(person);
        switch (field) {
            case "firstName" -> recordDialog.setFirstName(invalidValue);
            case "lastName" -> recordDialog.setLastName(invalidValue);
            case "telephone" -> recordDialog.setTelephone(invalidValue);
            case "dob" -> assertThat(recordDialog.dobValue()).isEmpty();
            default -> throw new IllegalArgumentException("No invalid-value handling for field '" + field + "'");
        }
        recordDialog.submit();
    }

    @Then("the submitted person data is saved to storage")
    public void theSubmittedPersonDataIsSavedToStorage() {
        Path file = PersonStorage.save(context.person());
        context.setStoredPersonFile(file);
        context.attach("Stored person (" + file + ")", PersonStorage.toJson(context.person()));

        assertThat(PersonStorage.load(file))
                .as("person read back from %s", file)
                .usingRecursiveComparison()
                .isEqualTo(context.person());
    }

    // --- update -------------------------------------------------------------------

    @When("the user updates that record with:")
    public void theUserUpdatesThatRecordWith(DataTable table) {
        PersonRecord original = context.person();
        PersonRecord updated = new PersonRecord(original);
        RecordMapper.applyTable(updated, withGeneratedValues(table));

        recordDialog = dashboard
                .recordCard(original.getFirstName(), original.getLastName())
                .openEditDialog()
                .fill(updated)
                .submit();
        context.setPerson(updated);
    }

    // --- delete -------------------------------------------------------------------

    @When("the user deletes that record")
    public void theUserDeletesThatRecord() {
        PersonRecord person = context.person();
        deleteDialog = dashboard
                .recordCard(person.getFirstName(), person.getLastName())
                .openDeleteDialog()
                .confirm();
    }

    @When("the user tries to delete the {word} record")
    public void theUserTriesToDeleteTheRecordWithRelationship(String relationship) {
        deleteDialog = dashboard.recordCardByRelationship(relationship).openDeleteDialog().confirm();
    }

    // --- outcomes -----------------------------------------------------------------

    @Then("the success message {string} is displayed")
    public void theSuccessMessageIsDisplayed(String expected) {
        assertThat(dashboard.successMessage()).isEqualTo(expected);
    }

    @Then("the error message {string} is displayed")
    public void theErrorMessageIsDisplayed(String expected) {
        assertThat(dashboard.errorMessage()).isEqualTo(expected);
    }

    @Then("the field validation message {string} is displayed")
    public void theFieldValidationMessageIsDisplayed(String expected) {
        assertThat(recordDialog.fieldValidationMessages()).contains(expected);
    }

    @Then("the person is listed on the dashboard with the submitted details")
    public void thePersonIsListedOnTheDashboardWithTheSubmittedDetails() {
        closeRecordDialog();
        PersonRecord expected = context.person();

        PersonRecord shown = dashboard.recordCard(expected.getFirstName(), expected.getLastName()).read();

        assertThat(shown)
                .as("record card of %s", expected.fullName())
                .usingRecursiveComparison()
                .ignoringFields(NOT_ON_THE_CARD)
                .isEqualTo(expected);
    }

    @Then("the person is no longer listed on the dashboard")
    public void thePersonIsNoLongerListedOnTheDashboard() {
        PersonRecord person = context.person();
        dashboard = deleteDialog.waitUntilClosedAfterDelete();
        dashboard.waitUntilRecordIsRemoved(person.getFirstName(), person.getLastName());

        assertThat(dashboard.listedFullNames()).doesNotContain(person.fullName());
    }

    @Then("the {word} record is still listed on the dashboard")
    public void theRecordIsStillListedOnTheDashboard(String relationship) {
        dashboard = deleteDialog.dismiss();
        assertThat(dashboard.recordCardByRelationship(relationship).isDisplayed())
                .as("%s record card is displayed", relationship)
                .isTrue();
    }

    @Then("the person is not listed on the dashboard")
    public void thePersonIsNotListedOnTheDashboard() {
        closeRecordDialog();
        assertThat(dashboard.listedFullNames()).doesNotContain(context.person().fullName());
    }

    /**
     * Turns the vertical data table into a map and replaces the {random} placeholder with random
     * letters, e.g. "FAKEUpd{random}" -> "FAKEUpdkqzvbn", so hard-coded names never collide.
     */
    private static Map<String, String> withGeneratedValues(DataTable table) {
        Map<String, String> values = new LinkedHashMap<>();
        table.asMap(String.class, String.class).forEach((field, value) -> values.put(field,
                value == null ? null : value.replace("{random}", TestDataFactory.randomLetters(6))));
        return values;
    }

    private void closeRecordDialog() {
        if (recordDialog != null) {
            dashboard = recordDialog.close();
            recordDialog = null;
        }
    }
}
